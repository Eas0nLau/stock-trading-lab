def 计算承接指标(前日股票, 当日行情, 当日股票代码=None):
    前日股票 = _按股票代码去重(前日股票)
    前日股票代码 = {取整数(stock.get("股票代码")) for stock in 前日股票}
    前日股票代码.discard(0)
    当日股票代码 = {取整数(code) for code in (当日股票代码 or set())}
    当日股票代码.discard(0)
    股票池数量 = len(前日股票)
    新晋级家数 = len(当日股票代码 - 前日股票代码)

    涨幅列表 = []
    振幅列表 = []
    晋级家数 = 0
    红盘家数 = 0
    大涨家数 = 0
    大跌家数 = 0
    炸板家数 = 0
    同板块留存家数 = 0

    for stock in 前日股票:
        code = 取整数(stock.get("股票代码"))
        if code in 当日股票代码:
            同板块留存家数 += 1
        quote = 当日行情.get(code)
        if not quote:
            continue

        pct_chg = 取可选浮点数(quote.get("pct_chg"))
        if pct_chg is None:
            continue
        涨幅列表.append(pct_chg)

        pre_close = 取可选浮点数(quote.get("pre_close"))
        high = 取可选浮点数(quote.get("high"))
        low = 取可选浮点数(quote.get("low"))
        high_pct = None
        if pre_close and pre_close > 0 and high is not None and low is not None:
            振幅列表.append((high - low) / pre_close * 100)
            high_pct = (high / pre_close - 1) * 100

        if pct_chg >= 晋级涨幅阈值:
            晋级家数 += 1
        if pct_chg > 0:
            红盘家数 += 1
        if pct_chg >= 大涨涨幅阈值:
            大涨家数 += 1
        if pct_chg <= 大跌涨幅阈值:
            大跌家数 += 1
        if high_pct is not None and high_pct >= 晋级涨幅阈值 and pct_chg < 晋级涨幅阈值:
            炸板家数 += 1

    有效样本数 = len(涨幅列表)
    return {
        "前日股票池数量": 股票池数量,
        "有效样本数": 有效样本数,
        "行情覆盖率": _百分比(有效样本数, 股票池数量) if 股票池数量 else None,
        "平均涨跌幅": _平均值(涨幅列表),
        "中位数涨跌幅": 保留小数(statistics.median(涨幅列表), 2) if 涨幅列表 else None,
        "平均振幅": _平均值(振幅列表),
        "涨幅标准差": 保留小数(statistics.pstdev(涨幅列表), 2) if len(涨幅列表) > 1 else 0.0 if 涨幅列表 else None,
        "晋级家数": 晋级家数,
        "晋级率": _百分比(晋级家数, 股票池数量) if 股票池数量 else None,
        "新晋级家数": 新晋级家数,
        "新晋级率": _百分比(新晋级家数, 股票池数量) if 股票池数量 else None,
        "红盘家数": 红盘家数,
        "红盘率": _百分比(红盘家数, 有效样本数) if 有效样本数 else None,
        "大涨家数": 大涨家数,
        "大涨率": _百分比(大涨家数, 有效样本数) if 有效样本数 else None,
        "大跌家数": 大跌家数,
        "大跌率": _百分比(大跌家数, 有效样本数) if 有效样本数 else None,
        "炸板家数": 炸板家数,
        "炸板率": _百分比(炸板家数, 有效样本数) if 有效样本数 else None,
        "同板块留存家数": 同板块留存家数,
        "同板块留存率": _百分比(同板块留存家数, 股票池数量) if 股票池数量 else None,
    }


def 判定热度阶段(当日板块数量, 当日榜单数据完整=True):
    if not 当日榜单数据完整:
        return "数据缺失"
    count = 取整数(当日板块数量)
    if count >= 高潮数量阈值:
        return "高潮"
    if count >= 热门板块入选数量阈值:
        return "升温"
    if count > 0:
        return "活跃"
    return "未上榜"


def 判定承接情绪(指标, 前日榜单数据完整=True):
    if not 前日榜单数据完整:
        return "数据缺失", "上一交易日榜单数据缺失"
    股票池数量 = 取整数(指标.get("前日股票池数量"))
    if 股票池数量 <= 0:
        return "无前日样本", "上一交易日该板块没有落库股票池"

    有效样本数 = 取整数(指标.get("有效样本数"))
    行情覆盖率 = 取浮点数(指标.get("行情覆盖率"))
    平均涨跌幅 = 取浮点数(指标.get("平均涨跌幅"))
    红盘率 = 取浮点数(指标.get("红盘率"))
    晋级家数 = 取整数(指标.get("晋级家数"))
    新晋级家数 = 取整数(指标.get("新晋级家数"))
    大跌率 = 取浮点数(指标.get("大跌率"))
    平均振幅 = 取浮点数(指标.get("平均振幅"))
    涨幅标准差 = 取浮点数(指标.get("涨幅标准差"))
    半数门槛 = max(1, math.ceil(股票池数量 * 强势延续晋级比例))
    数据充分 = 有效样本数 >= 最低有效样本数 and 行情覆盖率 >= 最低行情覆盖率

    # 晋级结构是硬条件：达到比例为强势延续，未达到但旧池仍有连板则为分化。
    强势命中项 = []
    if 晋级家数 >= 半数门槛:
        强势命中项.append(f"旧池晋级{晋级家数}只")
    if 新晋级家数 >= 半数门槛:
        强势命中项.append(f"新增涨停{新晋级家数}只")
    if 强势命中项:
        return "强势延续", (
            f"上一日股票池{股票池数量}只、晋级门槛{半数门槛}只，"
            f"{'、'.join(强势命中项)}达到门槛"
        )

    if 晋级家数 > 0:
        return "分化", (
            f"上一日股票池{股票池数量}只中有{晋级家数}只继续涨停，"
            f"未达到{半数门槛}只强势延续门槛"
        )

    if not 数据充分:
        return "数据不足", f"有效样本{有效样本数}只，行情覆盖率{行情覆盖率:.1f}%"

    if 平均涨跌幅 <= -2:
        return "退潮", "平均涨幅≤-2%"
    if 大跌率 >= 30:
        return "退潮", "大跌率≥30%"
    if 红盘率 <= 30 and 平均涨跌幅 < 0:
        return "退潮", "红盘率≤30%且平均涨幅为负"
    if 平均涨跌幅 > 0 and (红盘率 < 60 or 涨幅标准差 >= 4):
        return "分化", "板块平均上涨，但红盘覆盖不足或个股涨幅离散较大"
    if 平均涨跌幅 <= 0:
        return "分歧", "平均涨幅不高于0%，但未达到退潮阈值"
    if 平均振幅 >= 6 and 红盘率 < 60:
        return "分歧", "平均振幅≥6%且红盘率不足60%"
    return "良性承接", "平均涨幅、红盘率和波动结构保持良性"


def 判定综合状态(热度阶段, 承接情绪, 前日板块数量=0, 当日板块数量=0):
    # 高潮是热度硬条件，不能由平均涨幅、晋级率或情绪分间接触发。
    if 热度阶段 == "高潮":
        return "高潮"
    if 热度阶段 == "数据缺失" or 承接情绪 == "数据缺失":
        return "数据缺失"

    前日数量 = max(取整数(前日板块数量), 0)
    当日数量 = max(取整数(当日板块数量), 0)
    # 板块从上一交易日上榜变为当日未上榜，说明热度已经消失；
    # 此时样本规模只影响承接指标可信度，不能覆盖板块退潮信号。
    if 热度阶段 == "未上榜" and 前日数量 > 0:
        return "退潮"
    if 当日数量 <= 0:
        return "沉寂"
    # 只要旧池仍有连板但未达到强势延续门槛，综合状态也明确显示为分化。
    if 承接情绪 == "分化":
        return "分化"

    前日已入选 = 前日数量 >= 热门板块入选数量阈值
    当日已入选 = 当日数量 >= 热门板块入选数量阈值
    负向承接 = {"分化", "分歧", "退潮"}

    # 前后都处于低热度时，正向的小样本表现不能上升为板块强势。
    if not 前日已入选 and not 当日已入选:
        return 承接情绪 if 承接情绪 in 负向承接 else 热度阶段

    # 板块首次达到入选阈值属于升温，不能用此前少量股票的表现直接判强势。
    if not 前日已入选 and 当日已入选:
        return 热度阶段

    # 热度从入选区间跌回阈值以下，即使剩余股票表现较好也属于分化；
    # 数量只剩前日两成及以下时，按板块宽度快速坍缩判定退潮。
    if 前日已入选 and not 当日已入选:
        if 承接情绪 == "强势延续":
            return "强势延续"
        if 承接情绪 == "退潮" or 当日数量 / 前日数量 <= 0.2:
            return "退潮"
        return "分化"

    # 前后均达到入选阈值后，承接指标才可以决定强势延续、分化或退潮。
    if 承接情绪 in {"强势延续", "良性承接", "分化", "分歧", "退潮"}:
        return 承接情绪
    return 热度阶段


def 计算情绪分(指标, 当日板块数量, 当日榜单数据完整=True, 热度阶段=""):
    当日数量 = 取整数(当日板块数量) if 当日榜单数据完整 else 0
    热度基础分 = min(max(当日数量, 0), 高潮数量阈值) / 高潮数量阈值 * 高潮基础分
    股票池数量 = 取整数(指标.get("前日股票池数量"))
    有效样本数 = 取整数(指标.get("有效样本数"))

    if 股票池数量 <= 0 or 有效样本数 <= 0:
        score = 热度基础分
    else:
        平均涨跌幅 = 限制(取浮点数(指标.get("平均涨跌幅")), -5, 5)
        红盘率 = 取浮点数(指标.get("红盘率"))
        晋级率 = min(取浮点数(指标.get("晋级率")), 50)
        大跌率 = 取浮点数(指标.get("大跌率"))
        承接原始分 = (
            50
            + 平均涨跌幅 * 4
            + (红盘率 - 50) * 0.25
            + 晋级率 * 0.30
            - 大跌率 * 0.20
        )
        样本置信度 = 计算样本置信度(指标)
        承接修正分 = (承接原始分 - 50) * 样本置信度 * 承接修正系数
        score = 热度基础分 + 承接修正分

    if 热度阶段 == "高潮":
        score = 高潮基础分
    return 保留小数(限制(score, 0, 100), 1)


def 按综合状态校准情绪分(情绪分, 综合状态, 热度阶段):
    if 热度阶段 == "高潮":
        return 保留小数(高潮基础分, 1)
    状态分上限 = {
        "强势延续": 99,
        "良性承接": 95,
        "升温": 99,
        "分化": 85,
        "活跃": 99,
        "分歧": 70,
        "数据不足": 70,
        "退潮": 40,
        "沉寂": 20,
        "数据缺失": 0,
    }
    上限 = min(状态分上限.get(综合状态, 99), 99)
    if 综合状态 == "退潮" and 热度阶段 == "未上榜":
        上限 = min(上限, 30)
    return 保留小数(限制(min(取浮点数(情绪分), 上限), 0, 100), 1)


def 计算样本置信度(指标):
    有效样本数 = 取整数(指标.get("有效样本数"))
    行情覆盖率 = 限制(取浮点数(指标.get("行情覆盖率")), 0, 100)
    样本系数 = min(有效样本数 / 5, 1)
    return 保留小数(样本系数 * 行情覆盖率 / 100, 2)


def 生成判定摘要(前日股票池数量, 前日板块数量, 当日板块数量, 指标, 热度阶段, 承接情绪, 综合状态):
    前日数量 = 取整数(前日板块数量)
    当日数量 = 取整数(当日板块数量)
    if 热度阶段 == "未上榜" and 取整数(前日板块数量) > 0:
        return (
            f"上一交易日板块上榜{前日数量}只，今日未上榜，按热度消失判定为退潮；"
            f"上一日可跟踪股票池{前日股票池数量}只，今日有效样本{取整数(指标.get('有效样本数'))}只。"
        )
    if 前日股票池数量 <= 0:
        return f"板块上榜数量由{前日数量}只变为{当日数量}只；上一交易日无可跟踪股票池，综合判定为{综合状态}。"
    if 承接情绪 in {"数据不足", "数据缺失"}:
        return (
            f"板块上榜数量由{前日数量}只变为{当日数量}只；前日股票池{前日股票池数量}只，"
            f"今日有效样本{取整数(指标.get('有效样本数'))}只，"
            f"行情覆盖率{格式化百分比(指标.get('行情覆盖率'))}，综合判定为{综合状态}。"
        )
    if (
            前日数量 < 热门板块入选数量阈值
            and 当日数量 < 热门板块入选数量阈值
            and 承接情绪 in {"强势延续", "良性承接"}
    ):
        return (
            f"板块上榜数量由{前日数量}只变为{当日数量}只，前后均低于{热门板块入选数量阈值}只入选阈值；"
            f"前日股票池平均涨幅{格式化百分比(指标.get('平均涨跌幅'))}、旧池晋级{取整数(指标.get('晋级家数'))}只、"
            f"新增涨停{取整数(指标.get('新晋级家数'))}只，"
            f"仅代表小样本承接为{承接情绪}，综合按低热度判定为{综合状态}。"
        )
    return (
        f"板块上榜数量由{前日数量}只变为{当日数量}只；前日股票池{前日股票池数量}只，"
        f"今日平均涨幅{格式化百分比(指标.get('平均涨跌幅'))}，"
        f"平均振幅{格式化百分比(指标.get('平均振幅'))}，旧池晋级{取整数(指标.get('晋级家数'))}只，"
        f"新增涨停{取整数(指标.get('新晋级家数'))}只，"
        f"红盘率{格式化百分比(指标.get('红盘率'))}，大跌率{格式化百分比(指标.get('大跌率'))}；"
        f"承接情绪为{承接情绪}，综合判定为{综合状态}。"
    )


def _按股票代码去重(rows):
    result = {}
    for row in rows or []:
        code = 取整数(row.get("股票代码"))
        if code:
            result[code] = row
    return list(result.values())


def 是沪深主板非ST股票(股票代码, 股票名称=""):
    code = 取整数(股票代码)
    name = str(股票名称 or "").strip().upper()
    if "ST" in name:
        return False
    return 1 <= code <= 3999 or 600000 <= code <= 609999


def _平均值(values):
    return 保留小数(sum(values) / len(values), 2) if values else None


def _百分比(value, total):
    if not total:
        return None
    return 保留小数(value / total * 100, 1)


def 格式化百分比(value):
    number = 取可选浮点数(value)
    return "-" if number is None else f"{number:.1f}%"


def 限制(value, min_value, max_value):
    return max(min_value, min(max_value, value))


def 取整数(value):
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def 取可选整数(value):
    if value is None:
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def 取浮点数(value):
    try:
        return float(value or 0)
    except (TypeError, ValueError):
        return 0.0


def 取可选浮点数(value):
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def 保留小数(value, digits=2):
    if value is None:
        return None
    return round(float(value), digits)
